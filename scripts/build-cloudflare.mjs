// Finishes dist/ for Cloudflare after the regular build (npm run build):
// adds the static-asset _headers/_redirects files and the pre-rendered
// share cards. Netlify never runs this, so its deploys are unaffected
// while both hosts exist.
import { appendFileSync, cpSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");

if (!existsSync(path.join(DIST, "index.html"))) {
  console.error("❌ dist/index.html missing: run `npm run build` first.");
  process.exit(1);
}

cpSync(path.join(ROOT, "cloudflare", "_headers"), path.join(DIST, "_headers"));
// wrangler.jsonc's not_found_handling serves this for every unknown path.
if (!existsSync(path.join(DIST, "404.html"))) {
  console.error("❌ dist/404.html missing: scripts/prerender.mjs should have written it.");
  process.exit(1);
}

cpSync(path.join(ROOT, "cloudflare", "_redirects"), path.join(DIST, "_redirects"));

// One URL per page: every prerendered page is served at /route (from
// route.html), but Cloudflare would also serve /route/ with a 200 from
// route/index.html, which Google sees as a duplicate. 301 each /route/ to
// /route instead (one static rule per page). Static assets' own
// trailing-slash handling could only give a 307.
function prerenderedRoutes(dir, prefix = "") {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !["assets", "og"].includes(entry.name))
    .flatMap((entry) => {
      const route = `${prefix}/${entry.name}`;
      const sub = path.join(dir, entry.name);
      const own = existsSync(path.join(sub, "index.html")) ? [route] : [];
      return [...own, ...prerenderedRoutes(sub, route)];
    });
}
const slashRoutes = prerenderedRoutes(DIST).sort();
appendFileSync(
  path.join(DIST, "_redirects"),
  [
    "",
    "# Generated by scripts/build-cloudflare.mjs: trailing slash -> none.",
    "/index.html / 301",
    ...slashRoutes.map((route) => `${route}/ ${route} 301`),
    "",
  ].join("\n")
);

// Renders only the cards not already in .cache/og (see that script).
execFileSync(process.execPath, [path.join(ROOT, "scripts", "generate-og-images.mjs")], { stdio: "inherit" });

const ogSource = path.join(ROOT, ".cache", "og");
cpSync(ogSource, path.join(DIST, "og"), { recursive: true });
const count = readdirSync(path.join(DIST, "og", "net-worth")).length;
if (count !== 1001) {
  console.error(`❌ Expected 1001 share cards in dist/og/net-worth, found ${count}.`);
  process.exit(1);
}
console.log(`✅ dist/ ready for Cloudflare (404.html, _headers, _redirects + ${slashRoutes.length} trailing-slash 301s, 1001 share cards)`);
